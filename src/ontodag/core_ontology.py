"""The `core` pack, version 4: an upper ontology built by consensus, adopted by merge.

GENERATED — do not edit by hand. The list is produced in the sister repo
github.com/petfold/ontodag-core (tools/build.sh, commit 5bf8167) from WordNet 3.0, Wikidata,
SUMO, OpenCyc, schema.org, YAGO 4, BFO and DOLCE: every edge below is entailed
by at least two independent sources, or accepted by Peter's review; every
name is a hand-checked plain English word (a sense that shares its word with
another sense got its own name: book-copy, prepared-dish, capital-city).
`docs/CORE.md` is the design record; the decisions are in that repo's
`docs/UPPER.md` §6–§7.

**Taxonomy without teeth.** OntoDAG states subsumption and nothing else, so
this top offers branches and never fences (the disjointness wall). What it
gives is paths: a plane ticket is a transport ticket is a ticket is a
document, and `get document` finds it without anyone building the path.

**Ten branches**: `agent`, `attribute`, `cognition`, `event`, `field-of-study`, `information`, `physical-object`, `place`, `possession`, `substance`.

**It presumes the prelude.** Three edges connect the unit registry's kind
nodes to `attribute` (a measured dimension is an attribute), so `pack core`
applies the prelude first; the dimension heads themselves (weight, length,
temperature, ...) and every unit spelling belong to the registry and are
deliberately absent here. Quantities are values, not categories.

**What a version commits.** Names, and the truth of every edge — never
coverage. Adding nodes, inserting levels and deepening the top all
propagate by merge; a retraction or a rename does not. Versions are
therefore monotone: v2 is a strict superset of v1.
"""

